export function countryFromRange(rangeName: string, fallback: string): string {
  const lower = rangeName.toLowerCase();
  for (const [keywords, iso] of countryNames) {
    for (const keyword of keywords) {
      if (new RegExp(`\\b${keyword}\\b`).test(lower)) {
        return iso;
      }
    }
  }
  return fallback;
}

export function countryFromNumber(number: string): string {
  const digits = number.replace(/\D/g, "");
  if (digits.length === 0) {
    return "";
  }
  const match = countryNumeric.find(([prefix]) => digits.startsWith(prefix));
  return match?.[1] ?? "";
}

